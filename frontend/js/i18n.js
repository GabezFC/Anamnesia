export const DICT = { pt: PT, en: EN };

export function getLang() {
  try { const v = localStorage.getItem(LS_LANG); return LANGS.includes(v) ? v : 'pt'; } catch { return 'pt'; }
}

export function setLang(lang) {
  const l = LANGS.includes(lang) ? lang : 'pt';
  try { localStorage.setItem(LS_LANG, l); } catch { /* private mode: lives until reload only */ }
  if (typeof document !== 'undefined') document.documentElement.lang = l === 'en' ? 'en' : 'pt-BR';
  return l;
}

/** Locale tag for Intl / toLocaleString. */
export const locale = () => (getLang() === 'en' ? 'en-US' : 'pt-BR');

/** Translate `key`; `{name}` placeholders are replaced from `vars`. */
export function t(key, vars) {
  const s = DICT[getLang()][key] ?? PT[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Header toggle button. Switching reloads the page: every view is rebuilt in the new language. */
export function installLangToggle(host) {
  if (!host || host.querySelector('#lang-toggle')) return;
  document.documentElement.lang = getLang() === 'en' ? 'en' : 'pt-BR';
  const b = document.createElement('button');
  b.type = 'button';
  b.id = 'lang-toggle';
  b.className = 'lang-toggle';
  b.textContent = t('lang.toggle.label');
  b.setAttribute('aria-label', t('lang.toggle.aria'));
  b.addEventListener('click', () => { setLang(getLang() === 'pt' ? 'en' : 'pt'); location.reload(); });
  host.appendChild(b);
}
